def countingSort(arr):
    # Step 1: Create a frequency array for numbers from 0 to 99
    counts = [0] * 100
    for num in arr:
        counts[num] += 1

    # Step 2: Reconstruct the sorted list using the frequencies
    sorted_arr = []
    for num in range(100):
        sorted_arr.extend([num] * counts[num])

    return sorted_arr

