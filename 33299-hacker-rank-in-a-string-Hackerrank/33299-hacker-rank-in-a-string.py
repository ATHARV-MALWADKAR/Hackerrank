def hackerrankInString(s):
    target = "hackerrank"
    target_idx = 0
    target_len = len(target)
    
    for char in s:
        if char == target[target_idx]:
            target_idx += 1
            if target_idx == target_len:
                return "YES"
                
    return "NO"

