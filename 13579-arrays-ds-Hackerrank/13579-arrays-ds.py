def reverseArray(a):
    a_len = len(a)
    a_half_len = a_len / 2
    i,j = 0, a_len -1
    
while i < a_half_len:
    tmp = a[i]
    a[i] = a[j]
    a[j] = tmp
    i += 1
    j -= 1
        

