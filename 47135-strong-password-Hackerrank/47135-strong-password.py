# Complete the 'minimumNumber' function below.
#
# The function is expected to return an INTEGER.
# The function accepts following parameters:
#  1. INTEGER n
#  2. STRING password
#

def minimumNumber(n, password):
    numbers = "0123456789"
    lower_case = "abcdefghijklmnopqrstuvwxyz"
    upper_case = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    special_characters = "!@#$%^&*()-+"

    missing_types = 0

    if not any(c in numbers for c in password):
        missing_types += 1
    if not any(c in lower_case for c in password):
        missing_types += 1
    if not any(c in upper_case for c in password):
        missing_types += 1
    if not any(c in special_characters for c in password):
        missing_types += 1

    # Return the maximum between missing character types and length shortfall
    return max(missing_types, 6 - n)

