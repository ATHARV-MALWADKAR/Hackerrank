def pangrams(s):
    # Convert string to lowercase and store unique characters in a set
    unique_letters = set(s.lower())
    
    # Remove spaces if present
    unique_letters.discard(' ')
    
    # Check if all 26 letters of the English alphabet are present
    if len(unique_letters) == 26:
        return "pangram"
    else:
        return "not pangram"

