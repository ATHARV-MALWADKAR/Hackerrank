def stockmax(prices):
    max_profit = 0
    max_future_price = 0
    
    # Iterate backwards through the price list
    for price in reversed(prices):
        if price > max_future_price:
            max_future_price = price
        else:
            max_profit += max_future_price - price
            
    return max_profit

